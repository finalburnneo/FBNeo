static z8002_cpu *z8k_cpus[MAX_Z8002] = { NULL, NULL, NULL, NULL };
static z8002_cpu *z8k = NULL;
static INT32 z8k_active = -1;

static UINT8 core_read_byte(UINT32 a) { return Z8002ReadByte(a); }
static void core_write_byte(UINT32 a, UINT8 d) { Z8002WriteByte(a, d); }	// cheats

static void core_set_irq(INT32 cpu, INT32 line, INT32 state)
{
	INT32 active = z8k_active;
	if (active != cpu)
	{
		if (active != -1) Z8002Close();
		Z8002Open(cpu);
	}

	Z8002SetIRQLine(line, state);

	if (active != cpu)
	{
		Z8002Close();
		if (active != -1) Z8002Open(active);
	}
}

cpu_core_config Z8002Config =
{
	"z8002",
	Z8002Open,
	Z8002Close,
	core_read_byte,
	core_write_byte,
	Z8002GetActive,
	Z8002TotalCycles,
	Z8002NewFrame,
	Z8002Idle,
	core_set_irq,
	Z8002Run,
	Z8002RunEnd,
	Z8002Reset,
	Z8002Scan,
	Z8002Exit,
	0x10000,
	0
};

void Z8002Init(INT32 nCpu)
{
	if (nCpu < 0 || nCpu >= MAX_Z8002) {
		bprintf(PRINT_ERROR, _T("Z8002Init: bad cpu number %d\n"), nCpu);
		return;
	}

	if (z8k_cpus[nCpu] == NULL) {
		z8k_cpus[nCpu] = new z8002_cpu;
	}
	z8k_cpus[nCpu]->init();

	CpuCheatRegister(nCpu, &Z8002Config);
}

void Z8002Exit()
{
	for (INT32 i = 0; i < MAX_Z8002; i++) {
		if (z8k_cpus[i]) {
			delete z8k_cpus[i];
			z8k_cpus[i] = NULL;
		}
	}
	z8k = NULL;
	z8k_active = -1;
}

void Z8002Open(INT32 nCpu)
{
	if (nCpu < 0 || nCpu >= MAX_Z8002 || z8k_cpus[nCpu] == NULL) {
		bprintf(PRINT_ERROR, _T("Z8002Open: cpu %d not initialized\n"), nCpu);
		return;
	}
	z8k = z8k_cpus[nCpu];
	z8k_active = nCpu;
}

void Z8002Close()
{
	z8k = NULL;
	z8k_active = -1;
}

INT32 Z8002GetActive()
{
	return z8k_active;
}

void Z8002Reset()
{
	z8k->reset();
}

INT32 Z8002Run(INT32 nCycles)
{
	return z8k->run(nCycles);
}

void Z8002RunEnd()
{
	z8k->m_end_run = 1;
}

INT32 Z8002Idle(INT32 nCycles)
{
	z8k->m_total_cycles += nCycles;
	return nCycles;
}

INT32 Z8002TotalCycles()
{
	return z8k->m_total_cycles + (z8k->m_cycles_start - z8k->m_icount);
}

void Z8002NewFrame()
{
	for (INT32 i = 0; i < MAX_Z8002; i++) {
		if (z8k_cpus[i]) z8k_cpus[i]->m_total_cycles = 0;
	}
}

void Z8002SetIRQLine(INT32 line, INT32 state)
{
	// lines are level-triggered; HOLD/AUTO are treated as an assert
	z8k->set_input(line, (state == CPU_IRQSTATUS_NONE) ? CLEAR_LINE : ASSERT_LINE);
}

void Z8002SetRESETLine(INT32 state)
{
	if (state) {
		if (!z8k->m_in_reset) z8k->reset();
		z8k->m_in_reset = 1;
	} else {
		z8k->m_in_reset = 0;
	}
}

INT32 Z8002GetRESETLine()
{
	return z8k->m_in_reset;
}

UINT32 Z8002GetPC()
{
	return z8k->m_pc & 0xffff;
}

void Z8002MapMemory(UINT8 *ptr, UINT32 start, UINT32 end, INT32 flags)
{
	for (UINT32 i = start >> Z8K_PAGE_SHIFT; i <= (end >> Z8K_PAGE_SHIFT) && i < Z8K_PAGES; i++)
	{
		UINT8 *p = ptr ? (ptr + ((i << Z8K_PAGE_SHIFT) - (start & ~0xff))) : NULL;
		if (flags & MAP_READ)  z8k->m_mem_read[i]  = p;
		if (flags & MAP_WRITE) z8k->m_mem_write[i] = p;
		if (flags & MAP_FETCH) z8k->m_mem_fetch[i] = p;
	}
}

void Z8002SetReadWordHandler(UINT16 (*handler)(UINT32))       { z8k->m_read_word = handler; }
void Z8002SetWriteWordHandler(void (*handler)(UINT32, UINT16)) { z8k->m_write_word = handler; }
void Z8002SetReadByteHandler(UINT8 (*handler)(UINT32))         { z8k->m_read_byte = handler; }
void Z8002SetWriteByteHandler(void (*handler)(UINT32, UINT8))  { z8k->m_write_byte = handler; }
void Z8002SetReadPortHandler(UINT16 (*handler)(UINT16))        { z8k->m_read_port = handler; }
void Z8002SetWritePortHandler(void (*handler)(UINT16, UINT16)) { z8k->m_write_port = handler; }
void Z8002SetIRQAckCallback(UINT16 (*handler)(INT32))          { z8k->m_irq_ack = handler; }

UINT16 Z8002ReadWord(UINT32 address)              { return z8k->mem_rw(address); }
void Z8002WriteWord(UINT32 address, UINT16 data)  { z8k->mem_ww(address, data); }
UINT8 Z8002ReadByte(UINT32 address)               { return z8k->mem_rb(address); }

void Z8002WriteByte(UINT32 address, UINT8 data)
{
	// also patch fetch-only pages so cheats on ROM take effect
	address &= 0xffff;
	UINT8 *p = z8k->m_mem_fetch[address >> Z8K_PAGE_SHIFT];
	if (p && z8k->m_mem_write[address >> Z8K_PAGE_SHIFT] == NULL) p[address & 0xff] = data;
	z8k->mem_wb(address, data);
}

INT32 Z8002Scan(INT32 nAction)
{
	if (nAction & ACB_DRIVER_DATA)
	{
		for (INT32 i = 0; i < MAX_Z8002; i++)
		{
			z8002_cpu *c = z8k_cpus[i];
			if (c == NULL) continue;

			ScanVar(&c->m_regs, sizeof(c->m_regs), "Z8002 regs");
			SCAN_VAR(c->m_op);
			SCAN_VAR(c->m_ppc);
			SCAN_VAR(c->m_pc);
			SCAN_VAR(c->m_pc_b15);
			SCAN_VAR(c->m_psapseg);
			SCAN_VAR(c->m_psapoff);
			SCAN_VAR(c->m_fcw);
			SCAN_VAR(c->m_refresh);
			SCAN_VAR(c->m_nspseg);
			SCAN_VAR(c->m_nspoff);
			SCAN_VAR(c->m_irq_req);
			SCAN_VAR(c->m_irq_vec);
			SCAN_VAR(c->m_op_valid);
			SCAN_VAR(c->m_nmi_state);
			SCAN_VAR(c->m_irq_state);
			SCAN_VAR(c->m_mi);
			SCAN_VAR(c->m_halt);
			SCAN_VAR(c->m_in_reset);
			SCAN_VAR(c->m_total_cycles);
		}
	}

	return 0;
}
